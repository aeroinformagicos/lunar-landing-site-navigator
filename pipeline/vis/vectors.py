def build_vectors(web_data: Path, log: Callable[[str], None] = print) -> dict:
    """Every block, each with its own random stream (a block can change without moving the others)."""
    import time

    ctx = Context(web_data)
    meta = json.loads((Path(web_data) / "ephemeris.meta.json").read_text(encoding="utf-8"))
    if meta.get("synthetic") is not False:
        raise ValueError(f"{web_data}: the ephemeris table is synthetic; publish the real one (make ephem)")
    doc: dict = {
        "_meta": {
            "generator": "python -m pipeline.cli core-vectors (07_visibilidad.md §12.3)",
            "seed": SEED,
            "contract_version": meta.get("contract_version"),
            "masks": "site id (observer_height_m, default 2) or formula id: " + ", ".join(FORMULA_MASKS),
            "counts": dict(COUNTS),
        }
    }
    for i, name in enumerate(BLOCKS):
        t0 = time.perf_counter()
        doc[name] = BUILDERS[name](ctx, random.Random(SEED * 100 + i))
        log(f"  {name:<14} {len(doc[name]):>4} cases  {time.perf_counter() - t0:6.1f} s")
    return doc


def dumps(doc: dict) -> str:
    """One case per line, so that a regeneration shows as a readable diff."""
    parts = []
    for name, value in doc.items():
        if isinstance(value, list):
            body = ",\n".join("  " + json.dumps(c, separators=(",", ":"), allow_nan=False) for c in value)
            parts.append(f'"{name}": [\n{body}\n]')
        else:
            parts.append(f'"{name}": {json.dumps(value, allow_nan=False)}')
    return "{\n" + ",\n".join(parts) + "\n}\n"


def write_vectors(doc: dict, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dumps(doc), encoding="utf-8", newline="\n")
    return path
