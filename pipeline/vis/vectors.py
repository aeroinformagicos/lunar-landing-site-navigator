"""Shared Python → TypeScript vectors (07_visibilidad.md §12.3): ``python -m pipeline.cli core-vectors``.

Writes ``tests/golden/core_vectors.json`` with cases generated by the Python reference, one block per
function, in the layout that web/src/core/__tests__/vectors.test.ts reads (decisions D-65, D-82 g and
D-90; snake_case). Inputs are the published light data (``web/public/data``: ephemeris table,
``sites.json`` and ``horizon/<site>.json``), like the web reads them (07 §12.2). Masks are named by a
published site id (observer at 2 m unless the case says otherwise) or by a formula id (``flat:0``,
``flat:0.5``, ``tilt:0.3``, ``sine:1,3``).

The cases are drawn with a fixed seed, so a rerun on the same data gives the same file. Random cases
whose result sits on a threshold (a margin within 10⁻⁶° of 0, a night within 0.01 h of the limit…) are
redrawn: a last-bit difference between the languages must not flip a state.
"""

