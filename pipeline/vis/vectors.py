class Context:
    """Published data and the mask cache, resolved like ``maskOf`` in vectors.test.ts."""

    def __init__(self, web_data: Path):
        self.web_data = Path(web_data)
        self.table: EphemerisTable = load_table(self.web_data)
        doc = json.loads((self.web_data / "sites.json").read_text(encoding="utf-8"))
        self.defaults = doc["defaults"]
        self.sites = {s["id"]: s for s in doc["sites"]}
        self._masks: dict[tuple[str, float], Mask] = {}

    def mask(self, mask_id: str, observer_height_m: float = 2) -> Mask:
        key = (mask_id, observer_height_m)
        if key not in self._masks:
            if mask_id.split(":")[0] in ("flat", "tilt", "sine"):
                m = formula_mask(mask_id)
            else:
                s = self.sites[mask_id]
                if s["relief"] == "smooth" or not s["has_mask"]:
                    m = smooth_mask(observer_height_m, s["lat_deg"], s["lon_deg"])
                else:
                    m = load_mask(self.web_data, mask_id, observer_height_m)
            self._masks[key] = m
        return self._masks[key]

    def site_mask_frame(self, site_id: str, observer_height_m: float = 2):
        s = self.sites[site_id]
        m = self.mask(site_id, observer_height_m)
        return m, frame_for(s["lat_deg"], s["lon_deg"], m)

    def segment_of(self, site_id: str) -> str:
        """Apollo sites draw their dates from the `apollo` segment, the rest from `main`."""
        return "apollo" if site_id.startswith("apollo") else "main"

    def random_time(self, rng: random.Random, segment: str = "main", margin_s: float = 0) -> int:
        seg = next(s for s in self.table.segments if s.id == segment)
        return rng.randrange(int(seg.valid_from_unix), int(seg.valid_to_unix - margin_s))


def _body(b) -> dict:
    return {k: b[k] for k in ("az_deg", "el_deg", "range_km", "radius_deg")}


def _state_body(b) -> dict:
    return {
        "az_deg": b.az_deg, "el_deg": b.el_deg, "range_km": b.range_km, "radius_deg": b.radius_deg,
        "horizon_deg": b.horizon_deg, "margin_deg": b.margin_deg, "visible": b.visible,
    }


def _retry(rng: random.Random, draw: Callable[[random.Random], dict | None], tries: int = 50) -> dict:
    for _ in range(tries):
        case = draw(rng)
        if case is not None:
            return case
    raise RuntimeError("could not draw a case away from the thresholds")


